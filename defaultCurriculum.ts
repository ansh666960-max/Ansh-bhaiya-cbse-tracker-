export function createOfficialChaptersForSubject(subjectId: string): Chapter[] {
  const names = OFFICIAL_CBSE_CLASS_10_CHAPTERS[subjectId] || [];
  const now = new Date().toISOString();
  return names.map((name, index) => ({
    id: `${subjectId}-ch-${index + 1}-${Date.now().toString(36)}`,
    name,
    subjectId,
    tasks: { ...DEFAULT_TASKS_STATE },
    notes: '',
    createdAt: now,
    updatedAt: now,
  }));
}
